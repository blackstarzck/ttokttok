--
-- v1은 오프셋 페이지네이션이라 v3의 키셋 커서로 넘어가며 쓸모가 없어졌고
-- (§11-37), 유형 필터도 점수 고정도 없다. 저장소 전체에서 호출부가 없다 —
-- `src/`·`scripts/`·`docs/` 어디에도 `get_feed(`가 없고, `feed.ts`는
-- `get_feed_v4`만 부른다.
--
-- 이름이 달라 오버로드 모호성(PGRST203)은 없었다. 그래서 급하지 않았고,
-- 그 덕에 오래 남아 있었다. 그럼에도 지우는 이유는 **anon에 grant된 채로
-- 남아 있어서**다 — 아무도 안 쓰는데 anon 키를 가진 누구나 부를 수 있는
-- 엔드포인트다. 위험하지는 않다(security definer가 아니라 호출자 권한으로
-- 돌고 posts의 RLS가 그대로 적용돼 발행글만 나온다). 다만 쓰지 않는 표면을
-- 열어 둘 이유가 없고, 남겨 두면 다음 사람이 "현역인가?"를 매번 되묻는다.
--
-- 의존 객체가 없음을 확인하고 지운다(pg_depend 조회 결과 0건). cascade를
-- 쓰지 않는 것도 그래서다 — 딸린 것이 있다면 이 문장이 실패해야 한다.
-- ============================================================

