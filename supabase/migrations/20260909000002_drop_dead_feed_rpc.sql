-- 피드 RPC 계보에서 v1만 정리가 빠져 있었다:
--   v1  20260827000004에서 생성                    ← 여태 남아 있었다
--   v2  20260827000009 생성 → 20260828000001이 drop
--   v3  20260828000001 생성 → 20260904000001이 drop
